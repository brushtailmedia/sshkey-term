package client

// The user who generated a room key must be one of the members it was shared
// with.
//
// A current-epoch key is adopted only when its signed member list equals the
// roster this client sees and the generator is in that roster. The generator
// made the key and so knows it. Without the second condition a key made by
// someone outside the room passes the member-list check, because the list it
// was signed over is the honest one.
//
// Every case feeds its frames through handleInternal, as the read loop does.

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/json"
	"strings"
	"testing"

	"golang.org/x/crypto/ssh"

	"github.com/brushtailmedia/sshkey-term/internal/protocol"
)

const (
	reasonGeneratorOutsideRoster = "epoch key generated by a user who is not in the room roster"
	reasonDifferentMemberSet     = "epoch key wrapped for a different member set than the room roster"
)

// attestationWarning is the synthetic frame failClosedEpoch hands to the UI.
type attestationWarning struct {
	Room      string `json:"room"`
	Generator string `json:"generator"`
	Reason    string `json:"reason"`
}

// captureAttestationWarnings records every room_attestation_warning the client
// raises from here on.
func (h *editVerifyHarness) captureAttestationWarnings(t *testing.T) *[]attestationWarning {
	t.Helper()
	var got []attestationWarning
	h.alice.cfg.OnMessage = func(msgType string, raw json.RawMessage) {
		if msgType != "room_attestation_warning" {
			return
		}
		var w attestationWarning
		if err := json.Unmarshal(raw, &w); err != nil {
			t.Errorf("room_attestation_warning does not parse: %v", err)
		}
		got = append(got, w)
	}
	return &got
}

// deliver hands one frame to the client the way the read loop does.
func (h *editVerifyHarness) deliver(t *testing.T, msgType string, frame any) {
	t.Helper()
	raw, err := json.Marshal(frame)
	if err != nil {
		t.Fatalf("marshal %s: %v", msgType, err)
	}
	h.alice.handleInternal(msgType, raw)
}

// introduce makes a new user known to the client by a profile frame, which is
// all a server needs to send, and returns that user's signing key.
func (h *editVerifyHarness) introduce(t *testing.T, userID string) ed25519.PrivateKey {
	t.Helper()
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatalf("generate key for %s: %v", userID, err)
	}
	sshPub, err := ssh.NewPublicKey(pub)
	if err != nil {
		t.Fatalf("ssh public key for %s: %v", userID, err)
	}
	h.deliver(t, "profile", protocol.Profile{
		Type:           "profile",
		User:           userID,
		PubKey:         strings.TrimSpace(string(ssh.MarshalAuthorizedKey(sshPub))),
		KeyFingerprint: ssh.FingerprintSHA256(sshPub),
	})
	if h.alice.pubKeyForUser(userID) == nil {
		t.Fatalf("profile frame did not make %s's key known", userID)
	}
	return priv
}

// notAdopted fails unless the key of evRoom/evEpoch is absent everywhere a
// current key lives: memory, the current epoch number and the local store.
func (h *editVerifyHarness) notAdopted(t *testing.T, what string) {
	t.Helper()
	if h.adopted(t) {
		t.Errorf("%s: the key is held as an adopted key", what)
	}
	if got := h.alice.CurrentEpoch(evRoom); got != 0 {
		t.Errorf("%s: current epoch = %d, want 0", what, got)
	}
	if key, err := h.alice.store.GetEpochKey(evRoom, evEpoch); err != nil || key != nil {
		t.Errorf("%s: a key was persisted (%d bytes, err %v)", what, len(key), err)
	}
}

func TestEpochKey_GeneratorOutsideRosterRefused(t *testing.T) {
	cases := []struct {
		name   string
		roster []string
		// attacker returns the outsider's id and signing key.
		attacker func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey)
		// member returns a roster member's id and signing key, for the control.
		member func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey)
	}{
		{
			name:   "a user the client has never seen, made known by a profile frame",
			roster: []string{"usr_alice", "usr_bob"},
			attacker: func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey) {
				return "usr_mallory", h.introduce(t, "usr_mallory")
			},
			member: func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey) {
				return h.bobID, h.bobPriv
			},
		},
		{
			name:   "a user the client knows from elsewhere who is not in this room",
			roster: []string{"usr_alice", "usr_carol"},
			attacker: func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey) {
				return h.bobID, h.bobPriv
			},
			member: func(t *testing.T, h *editVerifyHarness) (string, ed25519.PrivateKey) {
				return "usr_carol", h.introduce(t, "usr_carol")
			},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			h := newEditVerifyHarness(t)
			warnings := h.captureAttestationWarnings(t)
			h.alice.setRoomMembers(evRoom, tc.roster)
			outsider, outsiderKey := tc.attacker(t, h)

			// Signed by the outsider over exactly the roster the client sees.
			h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, outsider, outsiderKey, tc.roster))

			h.notAdopted(t, "key generated outside the roster")
			if h.stashed() {
				t.Error("the refused key was kept for a roster refresh; no refresh can make it valid")
			}
			if len(*warnings) != 1 || (*warnings)[0].Generator != outsider || (*warnings)[0].Reason != reasonGeneratorOutsideRoster {
				t.Errorf("warnings = %+v, want one naming %s with reason %q", *warnings, outsider, reasonGeneratorOutsideRoster)
			}

			// Control: the same room and epoch from a member of the roster is adopted.
			member, memberKey := tc.member(t, h)
			raised := len(*warnings)
			h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, member, memberKey, tc.roster))
			if !h.adopted(t) || h.alice.CurrentEpoch(evRoom) != evEpoch {
				t.Errorf("a key generated by roster member %s was not adopted (current epoch %d)", member, h.alice.CurrentEpoch(evRoom))
			}
			if len(*warnings) != raised {
				t.Errorf("the member's key raised a warning: %+v", (*warnings)[raised:])
			}
		})
	}
}

// The check is made on the roster that matched the signed list, also when that
// roster only arrives with the refresh.
func TestEpochKey_GeneratorCheckedAfterRosterRefresh(t *testing.T) {
	h := newEditVerifyHarness(t)
	h.discardSends()
	warnings := h.captureAttestationWarnings(t)
	roster := []string{"usr_alice", "usr_bob"}
	malloryKey := h.introduce(t, "usr_mallory")

	// No roster yet: the key waits for one.
	h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, "usr_mallory", malloryKey, roster))
	if !h.stashed() {
		t.Fatal("with no roster the key should wait for a refresh")
	}
	h.notAdopted(t, "key waiting for a roster")

	// The roster arrives and equals the signed list. The generator is not in it.
	h.deliver(t, "room_members_list", protocol.RoomMembersList{Type: "room_members_list", Room: evRoom, Members: roster})

	h.notAdopted(t, "key generated outside the refreshed roster")
	if h.stashed() {
		t.Error("the waiting key was not cleared")
	}
	if len(*warnings) != 1 || (*warnings)[0].Reason != reasonGeneratorOutsideRoster {
		t.Errorf("warnings = %+v, want one with reason %q", *warnings, reasonGeneratorOutsideRoster)
	}

	// Control: a member's key for the same epoch is adopted against that roster.
	h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, h.bobID, h.bobPriv, roster))
	if !h.adopted(t) {
		t.Error("a key generated by a roster member was not adopted after the refresh")
	}
}

// Keep: a member's key delivered as a frame is adopted and raises nothing.
func TestEpochKey_GeneratorInRosterAdopted(t *testing.T) {
	h := newEditVerifyHarness(t)
	warnings := h.captureAttestationWarnings(t)
	roster := []string{"usr_alice", "usr_bob"}
	h.alice.setRoomMembers(evRoom, roster)

	h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, h.bobID, h.bobPriv, roster))

	if !h.adopted(t) || h.alice.CurrentEpoch(evRoom) != evEpoch {
		t.Errorf("member's key not adopted (current epoch %d)", h.alice.CurrentEpoch(evRoom))
	}
	if len(*warnings) != 0 {
		t.Errorf("warnings = %+v, want none", *warnings)
	}
}

// Keep: the key of a rotation this user made, delivered back by the server (a
// second device, or the same device after a restart), is adopted.
func TestEpochKey_OwnRotationDeliveredBackIsAdopted(t *testing.T) {
	h := newEditVerifyHarness(t)
	warnings := h.captureAttestationWarnings(t)
	roster := []string{"usr_alice", "usr_bob"}
	h.alice.setRoomMembers(evRoom, roster)

	h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, h.alice.UserID(), h.alice.privKey, roster))

	if !h.adopted(t) || h.alice.CurrentEpoch(evRoom) != evEpoch {
		t.Errorf("own rotation not adopted (current epoch %d)", h.alice.CurrentEpoch(evRoom))
	}
	if len(*warnings) != 0 {
		t.Errorf("warnings = %+v, want none", *warnings)
	}
}

// Keep: a generator who has since left the room is still reported as a member
// list that does not match, after the one refresh. The generator check adds no
// alarm of its own here: it is only reached when the lists are equal.
func TestEpochKey_GeneratorWhoLeftKeepsTheMemberSetAlarm(t *testing.T) {
	h := newEditVerifyHarness(t)
	h.discardSends()
	warnings := h.captureAttestationWarnings(t)
	h.alice.setRoomMembers(evRoom, []string{"usr_alice", "usr_carol"}) // bob has left

	// Bob generated the key while he was a member, over a list that held him.
	h.deliver(t, "epoch_key", h.buildAttestedEpochKey(t, h.bobID, h.bobPriv, []string{"usr_alice", "usr_bob", "usr_carol"}))
	if !h.stashed() {
		t.Fatal("a member list that differs should wait for one refresh")
	}
	h.deliver(t, "room_members_list", protocol.RoomMembersList{Type: "room_members_list", Room: evRoom, Members: []string{"usr_alice", "usr_carol"}})

	h.notAdopted(t, "key signed over a list that differs from the roster")
	if len(*warnings) != 1 || (*warnings)[0].Reason != reasonDifferentMemberSet {
		t.Errorf("warnings = %+v, want one with reason %q", *warnings, reasonDifferentMemberSet)
	}
}
